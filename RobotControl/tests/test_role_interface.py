def test_layout_is_the_contract(contract, jm):
    obs = RoleObs(contract, {n: i for i, n in enumerate(jm.names)})
    assert obs.n_obs == 131
    assert tuple(s["name"] for s in contract["observation"]["slots"]) == ROLE_SLOTS
    at = 0
    for slot in contract["observation"]["slots"]:
        assert slot["start"] == at
        at += slot["size"]
    assert at == obs.n_obs


@pytest.mark.skipif(not GOLDEN.is_file(), reason="no golden_role_obs.npz for unitree_r1_a5")
def test_reproduces_the_golden(builder, contract):
    z = np.load(GOLDEN)
    assert str(z["interface_sha256_16"][0]) == contract["hashes"]["interface_sha256_16"]
    worst = 0.0
    for i in range(z["obs"].shape[0]):
        state = LowStateData(
            q=np.zeros(26),
            dq=np.zeros(26),
            tau=np.zeros(26),
            imu_quat=np.asarray(z["pelvis_quat"][i], dtype=np.float64),
            gyro=np.asarray(z["pelvis_angvel"][i], dtype=np.float64),
            accel=np.zeros(3),
            timestamp=0.0,
        )
        for name, value in json.loads(z["joint_pos_json"][i]).items():
            if name in builder.joint_index:
                state.q[builder.joint_index[name]] = value
        for name, value in json.loads(z["joint_vel_json"][i]).items():
            if name in builder.joint_index:
                state.dq[builder.joint_index[name]] = value
        got = builder.build(
            state,
            np.asarray(z["prev_action"][i], dtype=np.float64),
            np.asarray(z["command"][i], dtype=np.float64),
            t=float(z["gait_phase"][i]) * 0.8,
        )
        worst = max(worst, float(np.max(np.abs(got - z["obs"][i]))))
    assert worst <= TOLERANCE


def test_masked_roles_carry_no_signal(builder):
    state = LowStateData.zeros(26)
    state.q[:] = 0.5
    state.dq[:] = 1.0
    obs = builder.build(state, np.ones(28), command=(0, 0, 0))
    mask = builder.slice_of(obs, "role_mask")
    assert int(mask.sum()) == 26
    for role in ("toe_l", "toe_r"):
        i = builder.roles.index(role)
        for slot in ("joint_pos_rel", "joint_vel", "prev_action"):
            assert builder.slice_of(obs, slot)[i] == 0.0
    assert abs(float(builder.slice_of(obs, "morphology_onehot").sum()) - 1.0) < 1e-6


def test_gait_phase_only_when_commanded(builder):
    state = LowStateData.zeros(26)
    still = builder.build(state, np.zeros(28), command=(0, 0, 0), t=0.3)
    assert np.array_equal(builder.slice_of(still, "gait_phase"), np.zeros(2))
    moving = builder.build(state, np.zeros(28), command=(0.5, 0.0, 0.0), t=0.0)
    assert np.allclose(builder.slice_of(moving, "gait_phase"), [0.0, 1.0], atol=1e-6)


def test_action_map_holds_the_nominal_pose(contract, jm):
    amap = RoleActionMap(contract, jm)
    assert np.allclose(amap.targets(np.zeros(28)), amap.q_default)
    assert amap.unmapped_joints == []


def test_action_map_clips_and_ignores_masked_roles(contract, jm):
    amap = RoleActionMap(contract, jm)
    q = amap.targets(np.full(28, 5.0))
    assert np.all(q >= amap.lo - 1e-12) and np.all(q <= amap.hi + 1e-12)
    toe = amap.roles.index("toe_l")
    assert amap.mask[toe] == 0
    knee = amap.index["left_knee_joint"]
    assert q[knee] != amap.q_default[knee]


def test_gains_come_from_the_contract(contract, jm):
    amap = RoleActionMap(contract, jm)
    by_name = {j["name"]: j for j in contract["morphology"]["joints"]}
    for name, joint in by_name.items():
        i = amap.index[name]
        assert amap.kp[i] == pytest.approx(joint["kp"])
        assert amap.kd[i] == pytest.approx(joint["kd"])
        assert amap.scale[i] == pytest.approx(joint["action_scale"])


