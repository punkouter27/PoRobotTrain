class _FakeIfc:
    def __init__(self, joint_map):
        self.joint_map = joint_map
        self.is_simulation = True
        self.connected = True
        self.state = LowStateData.zeros(joint_map.num_joints)
        self.state.q[:] = joint_map.defaults
        self.sent = []

    def get_low_state(self):
        return self.state

    def send_low_cmd(self, q, kp, kd):
        self.sent.append((np.array(q), np.array(kp), np.array(kd)))

    def tick(self):
        pass

    def send_damping(self):
        self.sent.append(None)


class _FakePolicy:
    path = GLOBAL / "policy.onnx"

    def __init__(self, n_obs=131, n_actions=28, action=None):
        self.num_obs = n_obs
        self.num_actions = n_actions
        self.action = np.zeros(n_actions) if action is None else np.asarray(action, dtype=np.float32)
        self.last_infer_ms = 0.0
        self.obs_seen = []

    def infer(self, obs):
        self.obs_seen.append(np.array(obs))
        return self.action


def _role_deploy():
    return DeployConfig.from_dict(
        {
            "policy_name": "r1_role_stand",
            "step_dt": 0.02,
            "num_obs": 131,
            "num_actions": 28,
            "joint_names": [],
            "motor_slots": [],
            "default_joint_pos": [],
            "kp": [],
            "kd": [],
            "action_scale": [],
            "observations": [],
            "commands": {"vx": 1, "vy": 1, "wz": 1},
        }
    )


def _sidecar_onnx(tmp_path, contract, name="policy"):
    """A file plus a sidecar that matches the pinned contract; no ONNX runtime needed to load it."""
    import hashlib

    onnx = tmp_path / f"{name}.onnx"
    onnx.write_bytes(b"stub weights; only the hash is checked at load")
    digest = hashlib.sha256(onnx.read_bytes()).hexdigest()
    sc = {
        "policy_name": name,
        "creature": contract["creature"],
        "n_obs": contract["observation"]["n_obs"],
        "n_action": contract["action"]["n_action"],
        "interface_sha256": contract["hashes"]["interface_sha256"],
        "morphology_sha256": contract["hashes"]["morphology_sha256"],
        "physics_sha256": contract["hashes"]["physics_sha256"],
        "policy_sha256": digest,
        "status": "conforming",
    }
    onnx.with_suffix(".json").write_text(json.dumps(sc), encoding="utf-8")
    return onnx


def test_runner_drives_the_role_interface(tmp_path, jm, contract):
    onnx = _sidecar_onnx(tmp_path, contract)
    policy = _FakePolicy()
    policy.path = onnx
    itf = _FakeIfc(jm)
    runner = PolicyRunner(
        itf,
        policy,
        _role_deploy(),
        jm,
        safety=SafetyGuard(jm, SafetyConfig()),
        log_dir=None,
        realtime=False,
        status_hz=0,
    )
    assert runner.role is not None
    assert runner.obs_builder is None
    assert runner.role.n_obs == 131 and runner.role.n_action == 28

    info = runner.step_once(0.0)
    assert policy.obs_seen[0].shape == (131,)
    assert np.allclose(info["target"], contract_defaults(contract, jm), atol=1e-9)
    assert np.allclose(runner.kp_full, [j["kp"] for j in contract["morphology"]["joints"]])


def test_foreign_brain_is_loadable_but_flagged(tmp_path, jm, contract):
    """R13: another creature's brain is allowed through a matching interface, and marked foreign."""
    onnx = _sidecar_onnx(tmp_path, contract, name="foreign")
    sc = json.loads(onnx.with_suffix(".json").read_text(encoding="utf-8"))
    sc["creature"] = "go2"
    sc["morphology_sha256"] = "a" * 64
    onnx.with_suffix(".json").write_text(json.dumps(sc), encoding="utf-8")
    iface = for_policy(types.SimpleNamespace(path=onnx, num_obs=131, num_actions=28), jm)
    assert iface is not None and iface.foreign and iface.trained_for == "go2"


def test_runner_refuses_a_stale_role_policy(tmp_path, jm, contract):
    onnx = _sidecar_onnx(tmp_path, contract)
    sc = json.loads(onnx.with_suffix(".json").read_text(encoding="utf-8"))
    sc["interface_sha256"] = "0" * 64
    onnx.with_suffix(".json").write_text(json.dumps(sc), encoding="utf-8")
    policy = _FakePolicy()
    policy.path = onnx
    with pytest.raises(C.ContractMismatch):
        PolicyRunner(_FakeIfc(jm), policy, _role_deploy(), jm, safety=SafetyGuard(jm, SafetyConfig()), log_dir=None)


def contract_defaults(contract, jm):
    out = np.zeros(jm.num_joints)
    index = {n: i for i, n in enumerate(jm.names)}
    for j in contract["morphology"]["joints"]:
        out[index[j["name"]]] = float(j.get("default") or 0.0)
    return out
