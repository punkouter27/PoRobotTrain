def test_foreign_sidecar_is_refused(tmp_path, jm):
    onnx = tmp_path / "policy.onnx"
    onnx.write_bytes(b"not really an onnx, but the hash is what matters here")
    sc = {
        "policy_name": "policy",
        "n_obs": 131,
        "n_action": 28,
        "interface_sha256": "0" * 64,
        "morphology_sha256": "0" * 64,
        "physics_sha256": "0" * 64,
        "policy_sha256": "0" * 64,
    }
    (tmp_path / "policy.json").write_text(json.dumps(sc), encoding="utf-8")
